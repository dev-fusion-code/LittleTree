unsigned long colorFor(char c, double health, double moisture) {
  // Foliage and blossoms: y (sunlit rim), L (light green), l (mid green), G (forest green), g (dark green), k (shadow crevice), f (petal), w (petal highlight)
  if (c == 'y' || c == 'L' || c == 'l' || c == 'G' || c == 'g' || c == 'k' || c == 'f' || c == 'w') {
    if (c == 'f') return 0xf5aac3;
    if (c == 'w') return 0xffebf5;
    if (health >= 70.0) {
      switch (c) {
        case 'y': return 0xc8f05a;
        case 'L': return 0xa1c95a;
        case 'l': return 0x70ad4a;
        case 'G': return 0x438b45;
        case 'g': return 0x2e6b3b;
        case 'k': return 0x1a4424;
      }
    } else if (health >= 40.0) {
      switch (c) {
        case 'y': return 0xc2cf4d;
        case 'L': return 0xa9ad52;
        case 'l': return 0x82963f;
        case 'G': return 0x5e7c3a;
        case 'g': return 0x455f30;
        case 'k': return 0x2b3d1f;
      }
    } else if (health >= 20.0) {
      switch (c) {
        case 'y': return 0xc5b84c;
        case 'L': return 0xb39c4d;
        case 'l': return 0x93803c;
        case 'G': return 0x746631;
        case 'g': return 0x5a4f27;
        case 'k': return 0x3b3319;
      }
    } else {
      switch (c) {
        case 'y': return 0x9e8048;
        case 'L': return 0x8c6f3f;
        case 'l': return 0x755c34;
        case 'G': return 0x5e4b2a;
        case 'g': return 0x4a3c22;
        case 'k': return 0x302716;
      }
    }
  }

  // Bark, wood, and moss: b (dark), B (mid), t (grain), h (highlight), m (moss)
  if (c == 'b' || c == 'B' || c == 't' || c == 'h' || c == 'm') {
    if (c == 'm') return 0x52803e;
    if (health >= 25.0) {
      switch (c) {
        case 'b': return 0x754728;
        case 'B': return 0x995e32;
        case 't': return 0xa46e34;
        case 'h': return 0xc48744;
      }
    } else {
      switch (c) {
        case 'b': return 0x5e4537;
        case 'B': return 0x7a5b48;
        case 't': return 0x866750;
        case 'h': return 0x9c7860;
      }
    }
  }

  // Soil: 1 (base), 2 (crumb), 3 (dark shadow), 4 (highlight)
  if (c >= '1' && c <= '4') {
    if (moisture < 25.0) {
      switch (c) {
        case '1': return 0x8f755a;
        case '2': return 0xaa9072;
        case '3': return 0x6e563e;
        case '4': return 0xc2ab8d;
      }
    } else if (moisture > 76.0) {
      switch (c) {
        case '1': return 0x3d2719;
        case '2': return 0x533823;
        case '3': return 0x27190f;
        case '4': return 0x5e412b;
      }
    } else {
      switch (c) {
        case '1': return 0x6a4429;
        case '2': return 0x8f6336;
        case '3': return 0x4f321f;
        case '4': return 0xb38349;
      }
    }
  }

  return 0;
}

